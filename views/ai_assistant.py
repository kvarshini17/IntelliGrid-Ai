def _build_system_context(record: dict) -> str:
    """Build context from a selected dataset record."""
    if not record:
        return ""

    lines = ["Selected energy record:"]
    for key, value in record.items():
        if pd.notna(value):
            lines.append(f"- {key}: {value}")

    return "\n".join(lines)


def _answer_simple_question(question: str, df: pd.DataFrame):
    """
    Answer simple greetings and supported room-energy questions directly.

    Return a result dictionary when handled; otherwise return None
    so the RAG pipeline can answer the question.
    """
    normalized = question.strip().lower()
    normalized = re.sub(r"[!.?,]+$", "", normalized)

    # Handle greetings without retrieving knowledge-base passages.
    greeting_pattern = (
        r"^(hi|hello|hey|hi there|hello there|"
        r"good morning|good afternoon|good evening)$"
    )

    if re.fullmatch(greeting_pattern, normalized):
        return {
            "answer": (
                "Hello! I'm IntelliGrid AI. You can ask me about "
                "energy consumption, room usage, anomalies, and "
                "energy-saving recommendations."
            ),
            "mode": "direct",
            "sources": [],
        }

    # Handle questions about the room with the highest total energy use.
    mentions_room = "room" in normalized or "which" in normalized
    mentions_highest = any(
        word in normalized
        for word in ("highest", "maximum", "max", "most", "top")
    )
    mentions_energy = any(
        word in normalized
        for word in (
            "usage",
            "energy",
            "consumption",
            "consumes",
            "consumed",
            "using",
        )
    )

    if mentions_room and mentions_highest and mentions_energy:
        required_columns = {"room_id", "energy_consumption"}

        if not required_columns.issubset(df.columns):
            return {
                "answer": (
                    "I couldn't calculate the room with the highest "
                    "energy usage because the dataset must contain "
                    "'room_id' and 'energy_consumption' columns."
                ),
                "mode": "direct",
                "sources": [],
            }

        energy_df = df[["room_id", "energy_consumption"]].copy()
        energy_df["energy_consumption"] = pd.to_numeric(
            energy_df["energy_consumption"], errors="coerce"
        )
        energy_df = energy_df.dropna(
            subset=["room_id", "energy_consumption"]
        )

        if energy_df.empty:
            return {
                "answer": (
                    "There are no valid room-energy records available "
                    "to calculate the highest energy usage."
                ),
                "mode": "direct",
                "sources": [],
            }

        room_totals = (
            energy_df.groupby("room_id", as_index=False)
            ["energy_consumption"]
            .sum()
            .sort_values("energy_consumption", ascending=False)
        )

        highest_room = room_totals.iloc[0]
        room_id = highest_room["room_id"]
        total_energy = highest_room["energy_consumption"]

        return {
            "answer": (
                f"Based on the available dataset, **Room {room_id}** "
                f"has the highest total recorded energy consumption: "
                f"**{total_energy:,.2f}** in the dataset's recorded "
                f"energy units. This is the sum of its recorded "
                f"'energy_consumption' values, not an average."
            ),
            "mode": "direct",
            "sources": [],
        }

    # Let the RAG pipeline handle all other questions.
    return None


def _answer_label(mode: str) -> str:
    """Explain how an answer was produced."""
    if mode == "direct":
        return (
            "Answered directly from the greeting handler "
            "or dataset calculation."
        )

    if mode == "null":
        return (
            "Knowledge-base retrieval fallback; no active LLM "
            "provider was used."
        )

    if mode == "fallback":
        return (
            "Retrieval fallback; the LLM could not generate an answer."
        )

    if mode == "no_evidence":
        return (
            "No sufficiently relevant knowledge-base evidence was found."
        )

    return (
        f"Generated by the '{mode}' LLM provider using the "
        "retrieved passages and any supplied record context."
    )


def _render_disclosure(use_record: bool) -> None:
    """Display a short explanation of the assistant's limitations."""
    st.caption(
        "IntelliGrid AI answers questions using dataset calculations "
        "or retrieved knowledge-base information. Verify important "
        "energy-related decisions against the underlying data."
    )

    if use_record:
        st.caption(
            "Selected-record context is enabled where supported."
        )


def render(
    df: pd.DataFrame,
    summary_df: pd.DataFrame,
    pipeline_results: list,
):
    """Render the IntelliGrid AI assistant page."""
    st.header("IntelliGrid AI Assistant")

    st.write(
        "Ask questions about your energy dataset or the information "
        "available in the knowledge base."
    )

    # Optional record context for RAG questions.
    use_record = st.checkbox(
        "Use the first dataset record as additional context",
        value=False,
        help=(
            "When enabled, the first row of the dataset is supplied "
            "as context to the RAG pipeline."
        ),
    )

    selected_record = None

    if use_record and not df.empty:
        selected_record = df.iloc[0].to_dict()

        with st.expander("Dataset record being used"):
            st.json(
                {
                    key: (
                        value.item()
                        if hasattr(value, "item")
                        else value
                    )
                    for key, value in selected_record.items()
                }
            )

    _render_disclosure(use_record)

    if "chat_history" not in st.session_state:
        st.session_state.chat_history = []

    if st.button("Clear conversation"):
        st.session_state.chat_history = []
        st.rerun()

    # Display previous messages.
    for entry in st.session_state.chat_history:
        with st.chat_message("user"):
            st.markdown(entry["question"])

        with st.chat_message("assistant"):
            st.markdown(entry["answer"])
            st.caption(_answer_label(entry.get("mode", "unknown")))

            sources = entry.get("sources", [])
            if sources:
                with st.expander("Retrieved sources"):
                    for source in sources:
                        st.write(source)

    question = st.chat_input(
        "Ask about energy consumption or recommendations..."
    )

    if question:
        system_context = (
            _build_system_context(selected_record)
            if selected_record
            else None
        )

        # Try a direct greeting or dataset calculation first.
        result = _answer_simple_question(question, df)

        # Use the existing RAG pipeline for other questions.
        if result is None:
            with st.spinner(
                "Retrieving knowledge and generating answer..."
            ):
                result = answer_with_rag(
                    question,
                    system_context=system_context,
                )

        st.session_state.chat_history.append(
            {
                "question": question,
                "answer": result.get(
                    "answer",
                    "Sorry, I couldn't generate an answer.",
                ),
                "mode": result.get("mode", "unknown"),
                "sources": result.get("sources", []),
            }
        )

        st.rerun()
